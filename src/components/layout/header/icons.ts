/** Renders a header-menu icon by its lucide name, falling back to `fallback` (default Layout). */
export function MenuIcon({ name, fallback = "Layout", ...props }: { name?: string; fallback?: string } & LucideProps) {
  return createElement(icons[name ?? ""] ?? icons[fallback] ?? Layout, props);
}

